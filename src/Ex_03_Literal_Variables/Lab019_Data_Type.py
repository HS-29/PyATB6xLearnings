# Type Conversion (Casting) :-Python allows conversion from one data type to another.
a = "100"
print(int(a))
print(type(int(a)))

b = 25
print(str(b))
print(type(str(b)))

c = 100
print(float(c))
print(type(float(c)))

d = "Hello"
print(bool(d))
print(type(bool(d)))
